#!/usr/bin/env bash
#
# Regenerate docs/FILE_CATALOG.md — a complete inventory of the first-party
# files (framework core and vendored assets are summarised separately).
#
# Usage: scripts/gen-catalog.sh

set -euo pipefail

cd "$(dirname "$0")/.."
OUT="docs/FILE_CATALOG.md"

emit_section() {
  local title="$1"; shift
  local dirs=("$@")
  echo "### $title"
  echo
  echo "| File | Type | Size |"
  echo "|---|---|---:|"
  while IFS= read -r f; do
    [ -z "$f" ] && continue
    case "$f" in
      *":Zone.Identifier"|*"/index.html"|./.env) continue ;;
    esac
    local base type size
    base="${f##*/}"
    if [[ "$base" == *.* ]]; then type="${base##*.}"; else type="(none)"; fi
    size="$(wc -c <"$f" | tr -d ' ')"
    echo "| \`$f\` | $type | $size |"
  done < <(find "${dirs[@]}" -type f 2>/dev/null | sort)
  echo
}

{
  echo "# File catalog"
  echo
  echo "Auto-generated by \`scripts/gen-catalog.sh\`. First-party files only"
  echo "(runtime \`index.html\` placeholders omitted); the CodeIgniter core"
  echo "(\`system/\`) and vendored asset bundles (\`assets/grocery_crud/\`,"
  echo "\`admin_resources/\`) are summarised at the end."
  echo
  emit_section "Root" . -maxdepth 1
  emit_section "Application" application
  emit_section "Database" db
  emit_section "Docker" docker
  emit_section "Scripts" scripts
  emit_section "Docs" docs
  emit_section "Assets (project-owned)" assets/README.md assets/css assets/jquery_ui assets/print_jq
  emit_section "Web-root assets" imgs resources
  emit_section "Licences" licenses
  echo "## Vendored / framework (summarised)"
  echo
  echo "| Path | Description |"
  echo "|---|---|"
  echo "| \`system/\` | CodeIgniter 3.1.13 framework core (MIT) |"
  echo "| \`assets/grocery_crud/\` | Grocery CRUD 1.6.4 assets + themes (MIT/GPL-3.0) |"
  echo "| \`admin_resources/\` | SB Admin 2 (Bootstrap 3) admin theme (MIT) |"
  echo "| \`application/views/I18N/\` | I18N Arabic library (LGPL) |"
} >"$OUT"

echo "wrote $OUT ($(grep -c '^|' "$OUT") table rows)"
